"""Regenerate backend/requirements-ci.lock (hash-pinned wheels for CI).

Usage (from repo root, after changing backend/requirements*.txt):
    python scripts/lock_ci_requirements.py

CI runs on Linux x86_64 with CPython 3.14 and installs the lock with
`pip install --only-binary :all: --require-hashes --no-deps`, so every
package (including fyers-apiv3, which is installed without its stale pins)
needs an exact version and a wheel hash for that platform.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
LOCK = BACKEND / "requirements-ci.lock"
FYERS_SPEC = "fyers-apiv3==3.2.0"
PLATFORM_ARGS = [
    "--only-binary",
    ":all:",
    "--python-version",
    "3.14",
    "--implementation",
    "cp",
    "--platform",
    "manylinux_2_28_x86_64",
    "--platform",
    "manylinux2014_x86_64",
    "--platform",
    "manylinux_2_17_x86_64",
]
HEADER = """\
# Generated by scripts/lock_ci_requirements.py - do not edit by hand.
# Hash-pinned wheels for CI (Linux x86_64, CPython 3.14): requirements-dev.txt
# plus fyers-apiv3, which is installed without its stale pins.
"""


def resolve(tmp: Path, name: str, args: list[str]) -> dict[str, tuple[str, str]]:
    report = tmp / f"{name}.json"
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--quiet",
            "--ignore-installed",
            "--target",
            str(tmp / name),
            "--report",
            str(report),
            *PLATFORM_ARGS,
            *args,
        ],
        check=True,
        cwd=BACKEND,
    )
    data = json.loads(report.read_text(encoding="utf-8"))
    resolved: dict[str, tuple[str, str]] = {}
    for item in data["install"]:
        meta = item["metadata"]
        sha = item["download_info"]["archive_info"]["hashes"]["sha256"]
        resolved[meta["name"].lower()] = (meta["version"], sha)
    return resolved


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp = Path(tmp_dir)
        packages = resolve(tmp, "dev", ["-r", "requirements-dev.txt"])
        packages.update(resolve(tmp, "fyers", ["--no-deps", FYERS_SPEC]))
    lines = [f"{name}=={ver} --hash=sha256:{sha}" for name, (ver, sha) in sorted(packages.items())]
    LOCK.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(lines)} packages to {LOCK.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
